"""
Escrow payments — Phase 3.

Two directions, mirroring how `contracts.Milestone` already models the
lifecycle it plugs into: `EscrowCharge` covers Pay In (the client funding a
milestone through Swich's hosted checkout), `Payout` covers the automated
disbursement to the freelancer on release. `PayoutProfile` is the bank/wallet
destination a freelancer has to set up before any release can pay them —
`Payout` refuses to exist without one.

Gated by `SWICH_ENABLED`, off by default, same shape as every external
provider in this codebase (FCM, the five OAuth integrations, Sentry). Unlike
those, this one already has real sandbox credentials — see D41 — so it is
exercised against the genuine Swich sandbox, not only mocks.
"""

from __future__ import annotations

from django.conf import settings
from django.db import models

from core.crypto import EncryptedTextField
from core.models import TimestampedModel


class EscrowCharge(TimestampedModel):
    """One attempt to fund a milestone through Swich's Pay In checkout.

    A milestone can accumulate more than one of these — a failed or
    abandoned checkout does not block trying again — so this is a plain
    `ForeignKey`, not `OneToOne`. Exactly one should ever reach `PAID`.
    """

    class Status(models.TextChoices):
        CREATED = "created", "Checkout created"
        PAID = "paid", "Paid"
        FAILED = "failed", "Failed"
        EXPIRED = "expired", "Expired"

    milestone = models.ForeignKey(
        "contracts.Milestone", on_delete=models.CASCADE, related_name="escrow_charges"
    )
    #: Swich's `customerTransactionId` — generated by us, sent on checkout
    #: creation, and the join key every callback and inquiry uses to find
    #: its way back to this row. Unique because Swich treats it as one.
    customer_transaction_id = models.CharField(max_length=50, unique=True)
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    currency = models.CharField(max_length=3, default="PKR")
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.CREATED)
    #: Swich's own reference for the transaction, populated once the
    #: callback arrives — `None` until then.
    swich_order_id = models.CharField(max_length=100, blank=True)
    #: The verified callback body, kept for audit — the same reasoning as
    #: `integrations.models.ActivityEvent` keeping provider payloads rather
    #: than only their derived fields.
    callback_payload = models.JSONField(null=True, blank=True)
    paid_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["milestone", "status"])]

    def __str__(self) -> str:
        return f"EscrowCharge {self.customer_transaction_id} ({self.status})"


class PayoutProfile(TimestampedModel):
    """Where a freelancer's released milestone money actually goes.

    One per user. `account_number` and `cnic` are `EncryptedTextField` for
    the same reason the OTP secrets in `accounts.models` are — a bank
    account number and a national ID card number are exactly the pair a
    breach turns into fraud, and neither needs to be searched or filtered
    on, only read back once at payout time.
    """

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="payout_profile"
    )
    bank_code = models.CharField(max_length=20, blank=True)
    bank_name = models.CharField(max_length=100, blank=True)
    account_number = EncryptedTextField(blank=True)
    #: The name Swich's `fetch/title` lookup returned for this account —
    #: shown back to the freelancer as "you're about to receive money at:
    #: X" before they save, so a mistyped account number is caught by a
    #: name mismatch rather than a payout to a stranger.
    verified_account_title = models.CharField(max_length=200, blank=True)
    cnic = EncryptedTextField(blank=True)
    msisdn = models.CharField(max_length=20, blank=True)

    @property
    def is_complete(self) -> bool:
        return bool(
            self.bank_code and self.bank_name and self.account_number and self.cnic and self.msisdn
        )

    def __str__(self) -> str:
        return f"PayoutProfile({self.user_id})"


class Payout(TimestampedModel):
    """One attempt to disburse a released milestone to its freelancer via
    Swich IBFT.

    `ForeignKey` rather than `OneToOne` on `milestone` for the same reason
    as `EscrowCharge`: a failed IBFT call (a bad bank code, a transient
    gateway error) should not permanently block the freelancer from being
    paid — `release_milestone` retries by creating a new row, not by
    mutating a failed one.
    """

    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        PROCESSING = "processing", "Processing"
        PAID = "paid", "Paid"
        FAILED = "failed", "Failed"

    milestone = models.ForeignKey(
        "contracts.Milestone", on_delete=models.CASCADE, related_name="payouts"
    )
    freelancer = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="payouts_received"
    )
    customer_transaction_id = models.CharField(max_length=50, unique=True)
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    currency = models.CharField(max_length=3, default="PKR")
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.PENDING)
    #: Swich's `{stan, transactionId, authId, rrn}` response, or an error
    #: body on failure — kept whole rather than split into columns nobody
    #: has asked to query on yet.
    swich_response = models.JSONField(null=True, blank=True)
    failure_reason = models.TextField(blank=True)
    paid_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["milestone", "status"])]

    def __str__(self) -> str:
        return f"Payout {self.customer_transaction_id} ({self.status})"
